"""Write assets/results.js: every number the slides chart, read from the repo.

The sources are the report's sources: captured/*.csv (bare-metal runs and the Tracee
capture) and the results/ that scripts/run_demo.sh regenerates (the simulation).

    python3 tools/extract_data.py <repo> <results-dir> [out.js]

<results-dir> is normally <repo>/results after scripts/run_demo.sh. Needs pandas
(the repo's .venv has it). The output is a plain <script>, so the deck also runs
from file:// where fetch() of a JSON file would be blocked.
"""
import json
import sys
from datetime import date
from pathlib import Path

import pandas as pd

repo, res = Path(sys.argv[1]), Path(sys.argv[2])
out_path = Path(sys.argv[3]) if len(sys.argv) > 3 else Path(__file__).resolve().parent.parent / "assets/results.js"
cap = repo / "captured"
out = {}

# G1: per-scan catch rate at the 0.037 s interval, scans pooled over reps
g1 = pd.read_csv(cap / "g1_scan.csv")
a = g1[g1.interval_s == 0.037].groupby(["variant", "dwell_ms"], dropna=False)[["scans", "catches"]].sum()
out["g1"] = {
    v: {("all" if pd.isna(d) else f"{d:g}"): {"rate": r.catches / r.scans, "scans": int(r.scans)} for (vv, d), r in a.iterrows() if vv == v}
    for v in sorted(a.index.get_level_values(0).unique())
}

# G2: tight-loop slowdown and fault rate per variant (median over reps and dwells),
# evasion range over the per-dwell medians
g2 = pd.read_csv(cap / "g2_pareto.csv")
per_dwell = g2.groupby(["variant", "dwell_ms"], dropna=False).evasion_rate.median()
out["g2"] = {
    v: {
        "slowdown": float(d.slowdown_vs_v1.median()),
        "faults_per_s": float(d.faults_per_s.median()),
        "evasion_min": float(per_dwell[v].min()),
        "evasion_max": float(per_dwell[v].max()),
    }
    for v, d in g2.groupby("variant")
}

# Simulation (results/ from scripts/run_demo.sh)
g3 = pd.read_csv(res / "aggregate_g3.csv")
mim = pd.read_csv(res / "aggregate_mimicry.csv").set_index("policy")
ml = sorted(mim.index[mim.group.str.startswith("ml")])
cols = ["group", "miss_rate", "p95_latency", "roc_auc_benign", "overhead_ms", "monitor_share", "benign_share"]
out["policies"] = {p: {k: (None if pd.isna(v) else v) for k, v in r.items()} for p, r in mim[cols].to_dict("index").items()}

m = g3[g3.mimicry == True].set_index(["policy", "condition"]).p95_latency.unstack()  # noqa: E712
ratio = m.div(m["none"], axis=0)
out["g3_sim"] = {p: {c: float(ratio.loc[p, c]) for c in ["hiding", "starvation", "coupled"]} for p in ["baseline", "iforest", "rf", "cgroup_weight"]}

# The scenario's monitor shares under the coupled attack (the framework slide)
cpl = g3[g3.condition == "coupled"]
share = lambda mimicry, pols: float(cpl[(cpl.mimicry == mimicry) & cpl.policy.isin(pols)].monitor_share.median())  # noqa: E731
naive_ml = cpl[(cpl.mimicry == False) & cpl.policy.isin(ml)]  # noqa: E712
out["shares"] = {
    "no_attack": float(g3[(g3.condition == "none") & (g3.policy == "baseline")].monitor_share.median()),
    "eevdf": share(True, ["baseline"]),
    "ml_fooled": share(True, ml),
    "ml_detected": share(False, ml),
    "reservation": share(True, ["invariant"]),
}
out["naive_ml"] = {"auc_min": float(naive_ml[["roc_auc", "roc_auc_benign"]].min().min()), "miss_max": float(naive_ml.miss_rate.max())}

# Real kernel (captured/coupled_live.csv): medians over reps
cl = pd.read_csv(cap / "coupled_live.csv")
c = cl.groupby(["policy", "condition"])[["scans_per_s", "catches", "p95_scan_ms"]].median()
out["live"] = {p: {k: c.loc[(p, k)].to_dict() for k in ["none", "hiding", "starvation", "coupled"]} for p in ["eevdf", "cgroup_weight", "sched_fifo"]}
out["live_p95_max"] = float(cl.p95_scan_ms.max())

# Detection (captured/detection_g5.csv): five batches pooled
d = pd.read_csv(cap / "detection_g5.csv")
out["g5"] = d.groupby("detector")[["n_attackers", "n_benign", "caught", "false_alarms"]].sum().astype(int).to_dict("index")
out["g6b_ms"] = d.dropna(subset=["triage_ms_mean"]).triage_ms_mean.round(1).tolist()

header = (
    f"// Generated by tools/extract_data.py on {date.today()}; do not edit by hand.\n"
    "// Sources: captured/g1_scan.csv, g2_pareto.csv, coupled_live.csv, detection_g5.csv,\n"
    "// and results/aggregate_{g3,mimicry}.csv from scripts/run_demo.sh.\n"
)
out_path.write_text(header + "window.RTS = " + json.dumps(out, indent=1, allow_nan=False) + ";\n")
print("wrote", out_path)
